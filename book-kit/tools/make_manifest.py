#!/usr/bin/env python3
"""Writes <book>/manifest.js: every activity id in the book, in order (used for the 75% unlock and the dashboard).
   python3 book-kit/tools/make_manifest.py material-properties"""
import sys, json, http.server, threading, functools, pathlib
from playwright.sync_api import sync_playwright
book = sys.argv[1]; root = pathlib.Path(__file__).resolve().parent.parent.parent
class Q(http.server.SimpleHTTPRequestHandler):
    def log_message(self, *x): pass
srv = http.server.ThreadingHTTPServer(('127.0.0.1', 0), functools.partial(Q, directory=str(root)))
threading.Thread(target=srv.serve_forever, daemon=True).start()
with sync_playwright() as p:
    b = p.chromium.launch(executable_path='/usr/bin/google-chrome'); pg = b.new_page(viewport={'width': 1180, 'height': 820})
    pg.add_init_script('window.__NOGATE = 1')  # skip a workbook password lock while testing
    pg.goto(f'http://127.0.0.1:{srv.server_port}/{book}/index.html'); pg.wait_for_timeout(1200)
    pg.evaluate("BOOK_CONFIG.backend=''")
    pg.fill('#cv-name', 'M M'); pg.fill('#cv-email', 'm@' + pg.evaluate("BOOK_CONFIG.emailDomain")); 
    if pg.locator('#cv-class option').count() > 1: pg.select_option('#cv-class', index=1)
    pg.click('#next'); pg.wait_for_timeout(1000)
    n = pg.evaluate('Book.pages.length')
    for i in range(1, n): pg.evaluate(f'Book.go({i})'); pg.wait_for_timeout(2200)
    pages = pg.evaluate("Book.pages.filter(p=>p.ids.length).map((p)=>({id:p.id,title:p.title,n:Book.pages.indexOf(p),items:p.ids.map(id=>({id,label:p.meta[id].label,type:p.meta[id].type,max:p.meta[id].max}))}))")
    b.close()
ids = [it['id'] for pg_ in pages for it in pg_['items']]
(root / book / 'manifest.js').write_text('// generated by book-kit/tools/make_manifest.py — re-run after changing activities\nwindow.BOOK_MANIFEST = ' + json.dumps({'ids': ids, 'pages': pages}, indent=1) + ';\n')
print(len(pages), 'pages,', len(ids), 'activities')
